#!/usr/bin/env python3
"""
A stand-in IPTV provider for the QA run (docs/qa/QA-PLAN.md).

It serves everything a real subscription would, from media generated by make_media.sh:

  /playlist.m3u                M3U with groups, EPG ids, Hebrew names, catch-up, a 404 channel,
                               a failover pair, a direct MPEG-TS channel and a slow-start channel
  /guide.xml, /guide.xml.gz    XMLTV around "now" for every tvg-id in the playlist
  /big.m3u                     5,000 channels, for the scale scenario
  /malformed.m3u               an HTML error page with a 200, as some panels send
  /empty.m3u                   a valid header and no channels
  /admin/outage?secs=N         drop every other request for N seconds (a network outage)
  /switchable.m3u              the normal playlist until /admin/suspend, then the HTML page
                               (/admin/restore switches it back)
  /hls/<a|b|c>/live.m3u8       a sliding live window over the looped segments
  /ts/<a|b|c>.ts               a continuous MPEG-TS stream, paced in real time
  /slow/<a|b|c>/live.m3u8      the same live window after an 8-second stall
  /player_api.php, /xmltv.php  a minimal Xtream Codes panel (user qa / password qa123)
  /live|movie|series/qa/qa123/<id>.<ext>

Every request is appended to requests.jsonl so the run can assert what the app actually asked
for (user agent, how often it polls, whether it ever requested a URL it should not have).

Usage: server.py <media-dir> <log-dir> [port]
"""
import gzip
import json
import os
import re
import sys
import threading
import time
from datetime import datetime, timedelta, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

MEDIA = sys.argv[1]
LOGDIR = sys.argv[2]
PORT = int(sys.argv[3]) if len(sys.argv) > 3 else 8080
# The emulator reaches the host's loopback as 10.0.2.2.
BASE = os.environ.get("QA_BASE", f"http://10.0.2.2:{PORT}")
USER, PASS = "qa", "qa123"
T0 = time.time()
SEG = 2.0
WINDOW = 6
LOCK = threading.Lock()
SUSPENDED = threading.Event()
OUTAGE_UNTIL = [0.0]  # /admin/outage?secs=N: every other request is dropped until then
SUSPENDED_PAGE = "<html><body><h1>Account suspended</h1></body></html>"

os.makedirs(LOGDIR, exist_ok=True)


def segments(variant):
    d = os.path.join(MEDIA, variant)
    return sorted(f for f in os.listdir(d) if f.startswith("seg_") and f.endswith(".ts"))


SEGMENTS = {v: segments(v) for v in "abc"}

# ------------------------------------------------------------------ catalogue

GROUPS = ["News", "Sport", "Kids"]
CHANNELS = []  # (tvg_id, name, group, url, extra_attrs)
for i in range(1, 25):
    group = GROUPS[(i - 1) % 3]
    variant = "abc"[(i - 1) % 3]
    # The ?ch= tag is ignored when serving; it lets the request log tell one channel's stream
    # from another that shares its variant (QA-22: was the locked channel fetched?).
    CHANNELS.append((f"qa.ch{i:02d}", f"QA {group} {i:02d}", group,
                     f"{BASE}/hls/{variant}/live.m3u8?ch={i:02d}", f'tvg-chno="{i}"'))
CHANNELS += [
    ("qa.hebrew", "ערוץ בדיקה עברית", "News", f"{BASE}/hls/b/live.m3u8", 'tvg-chno="25"'),
    ("qa.catchup", "QA Catchup", "News", f"{BASE}/hls/c/live.m3u8",
     'tvg-chno="26" catchup="shift" catchup-days="3"'),
    ("qa.broken", "QA Broken 404", "Sport", f"{BASE}/hls/missing/live.m3u8", 'tvg-chno="27"'),
    # Same tvg-id twice: the app folds them into one channel with a backup URL (FR-PLB-17).
    ("qa.failover", "QA Failover", "Sport", f"{BASE}/hls/gone/live.m3u8", 'tvg-chno="28"'),
    ("qa.failover", "QA Failover", "Sport", f"{BASE}/hls/a/live.m3u8", 'tvg-chno="28"'),
    ("qa.ts", "QA Direct TS", "Kids", f"{BASE}/ts/b.ts", 'tvg-chno="29"'),
    ("qa.slow", "QA Slow Start", "Kids", f"{BASE}/slow/c/live.m3u8", 'tvg-chno="30"'),
]


def m3u():
    lines = [f'#EXTM3U url-tvg="{BASE}/guide.xml"']
    for tvg, name, group, url, extra in CHANNELS:
        lines.append(f'#EXTINF:-1 tvg-id="{tvg}" tvg-name="{name}" tvg-logo="{BASE}/logo/{tvg}.png" '
                     f'group-title="{group}" {extra},{name}')
        lines.append(url)
    return "\n".join(lines) + "\n"


def big_m3u(n=5000):
    lines = ["#EXTM3U"]
    for i in range(n):
        lines.append(f'#EXTINF:-1 tvg-id="big.{i}" group-title="Bulk {i % 50:02d}",Bulk channel {i:05d}')
        lines.append(f"{BASE}/hls/{'abc'[i % 3]}/live.m3u8?n={i}")
    return "\n".join(lines) + "\n"


def xmltv():
    now = datetime.now(timezone.utc).replace(minute=0, second=0, microsecond=0)
    fmt = "%Y%m%d%H%M%S +0000"
    ids = sorted({c[0] for c in CHANNELS} | {f"xc.{i}" for i in range(1, 13)})
    out = ['<?xml version="1.0" encoding="UTF-8"?>', '<tv generator-info-name="shidur-qa">']
    for cid in ids:
        out.append(f'<channel id="{cid}"><display-name>{cid}</display-name></channel>')
    for cid in ids:
        start = now - timedelta(hours=12)
        k = 0
        while start < now + timedelta(hours=24):
            end = start + timedelta(minutes=30)
            title = f"תוכנית {k}" if cid == "qa.hebrew" else f"{cid} show {k}"
            out.append(f'<programme start="{start.strftime(fmt)}" stop="{end.strftime(fmt)}" channel="{cid}">'
                       f'<title>{title}</title><desc>QA programme {k} on {cid}</desc></programme>')
            start, k = end, k + 1
    out.append("</tv>")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ Xtream

XC_LIVE = [{"num": i, "name": f"XC Live {i:02d}", "stream_id": i, "stream_icon": "",
            "epg_channel_id": f"xc.{i}", "category_id": str((i - 1) % 3 + 1),
            "tv_archive": 1 if i == 1 else 0, "tv_archive_duration": 2 if i == 1 else 0}
           for i in range(1, 13)]
XC_VOD = [{"num": i, "name": f"XC Movie {i}", "stream_id": 100 + i, "stream_icon": "",
           "category_id": "10", "container_extension": "mp4", "rating": "7.1", "year": "2024",
           "plot": f"QA movie number {i}"} for i in range(1, 7)]
XC_SERIES = [{"num": i, "name": f"XC Series {i}", "series_id": 200 + i, "cover": "",
              "category_id": "20", "plot": f"QA series {i}", "releaseDate": "2023-01-01", "rating": "8"}
             for i in range(1, 3)]


def xc_series_info(series_id):
    episodes = {}
    for season in (1, 2):
        episodes[str(season)] = [{"id": str(series_id * 100 + season * 10 + e), "episode_num": e,
                                  "title": f"S{season:02d}E{e:02d}", "container_extension": "mp4",
                                  "season": season, "info": {"plot": "QA episode"}}
                                 for e in (1, 2, 3)]
    return {"info": {"name": f"Series {series_id}"}, "episodes": episodes}


def xc_api(q):
    if q.get("username", [""])[0] != USER or q.get("password", [""])[0] != PASS:
        return 200, {"user_info": {"auth": 0}}
    action = q.get("action", [None])[0]
    if action is None:
        return 200, {"user_info": {"auth": 1, "status": "Active", "exp_date": str(int(time.time()) + 86400 * 30),
                                   "max_connections": "2", "active_cons": "0", "is_trial": "0",
                                   "allowed_output_formats": ["m3u8", "ts"]},
                     "server_info": {"timezone": "Asia/Jerusalem"}}
    table = {
        "get_live_categories": [{"category_id": str(i + 1), "category_name": f"XC {g}"} for i, g in enumerate(GROUPS)],
        "get_live_streams": XC_LIVE,
        "get_vod_categories": [{"category_id": "10", "category_name": "XC Movies"}],
        "get_vod_streams": XC_VOD,
        "get_series_categories": [{"category_id": "20", "category_name": "XC Series"}],
        "get_series": XC_SERIES,
    }
    if action == "get_series_info":
        return 200, xc_series_info(int(q.get("series_id", ["0"])[0]))
    return 200, table.get(action, [])


# ------------------------------------------------------------------ HLS live window

def live_playlist(variant):
    segs = SEGMENTS[variant]
    n = len(segs)
    seq = int((time.time() - T0) / SEG)
    disc_seq = (seq - 1) // n if seq > 0 else 0
    lines = ["#EXTM3U", "#EXT-X-VERSION:3", f"#EXT-X-TARGETDURATION:{int(SEG)}",
             f"#EXT-X-MEDIA-SEQUENCE:{seq}", f"#EXT-X-DISCONTINUITY-SEQUENCE:{disc_seq}"]
    for k in range(seq, seq + WINDOW):
        if k > 0 and k % n == 0:
            lines.append("#EXT-X-DISCONTINUITY")
        lines.append(f"#EXTINF:{SEG:.3f},")
        lines.append(f"seg/{segs[k % n]}")
    return "\n".join(lines) + "\n"


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "ShidurQA/1.0"

    def log_message(self, fmt, *args):  # silence stderr; requests.jsonl is the record
        pass

    def _log(self, status, size):
        rec = {"t": round(time.time() - T0, 2), "method": self.command, "path": self.path, "status": status,
               "bytes": size, "ua": self.headers.get("User-Agent"), "range": self.headers.get("Range")}
        with LOCK, open(os.path.join(LOGDIR, "requests.jsonl"), "a") as f:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    def _send(self, status, body, ctype):
        if isinstance(body, str):
            body = body.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)
        self._log(status, len(body))

    def _file(self, path, ctype):
        if not os.path.isfile(path):
            return self._send(404, "not found", "text/plain")
        size = os.path.getsize(path)
        rng = self.headers.get("Range")
        start, end = 0, size - 1
        m = re.match(r"bytes=(\d*)-(\d*)", rng or "")
        if m:
            if m.group(1):
                start = int(m.group(1))
                if m.group(2):
                    end = min(int(m.group(2)), size - 1)
            elif m.group(2):  # suffix range: the last N bytes
                start = max(0, size - int(m.group(2)))
        length = end - start + 1
        self.send_response(206 if m else 200)
        self.send_header("Content-Type", ctype)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(length))
        if m:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.end_headers()
        sent = 0
        if self.command != "HEAD":
            with open(path, "rb") as f:
                f.seek(start)
                while sent < length:
                    chunk = f.read(min(65536, length - sent))
                    if not chunk:
                        break
                    try:
                        self.wfile.write(chunk)
                    except (BrokenPipeError, ConnectionResetError):
                        break
                    sent += len(chunk)
        self._log(206 if m else 200, sent)

    def _ts_stream(self, variant):
        """A never-ending MPEG-TS stream at real-time pace, the way an Xtream `.ts` URL behaves."""
        segs = SEGMENTS[variant]
        self.send_response(200)
        self.send_header("Content-Type", "video/mp2t")
        self.send_header("Connection", "close")
        self.end_headers()
        sent, k = 0, int((time.time() - T0) / SEG)
        began = time.time()
        try:
            for i in range(900):  # bounded: 30 minutes at most per connection
                with open(os.path.join(MEDIA, variant, segs[(k + i) % len(segs)]), "rb") as f:
                    data = f.read()
                self.wfile.write(data)
                sent += len(data)
                # Stay one segment ahead of real time, like a live source.
                lag = began + (i * SEG) - time.time()
                if lag > 0:
                    time.sleep(lag)
        except (BrokenPipeError, ConnectionResetError):
            pass
        self.close_connection = True
        self._log(200, sent)

    def do_HEAD(self):
        self.do_GET()

    def do_GET(self):
        u = urlparse(self.path)
        p, q = u.path, parse_qs(u.query)
        if p == "/admin/outage":
            OUTAGE_UNTIL[0] = time.time() + float(q.get("secs", ["20"])[0])
            return self._send(200, "outage", "text/plain")
        if time.time() < OUTAGE_UNTIL[0] and not p.startswith("/admin") and p != "/health":
            # Hang up without a response, the way an unreachable network looks to the player.
            self.close_connection = True
            self._log(0, 0)
            return
        if p == "/playlist.m3u":
            return self._send(200, m3u(), "audio/x-mpegurl")
        if p == "/big.m3u":
            return self._send(200, big_m3u(), "audio/x-mpegurl")
        if p == "/switchable.m3u":
            # The normal playlist, until /admin/suspend makes it answer like a suspended account.
            if SUSPENDED.is_set():
                return self._send(200, SUSPENDED_PAGE, "text/html")
            return self._send(200, m3u(), "audio/x-mpegurl")
        if p == "/admin/suspend":
            SUSPENDED.set()
            return self._send(200, "suspended", "text/plain")
        if p == "/admin/restore":
            SUSPENDED.clear()
            return self._send(200, "restored", "text/plain")
        if p == "/empty.m3u":
            return self._send(200, "#EXTM3U\n", "audio/x-mpegurl")
        if p == "/malformed.m3u":
            return self._send(200, SUSPENDED_PAGE, "text/html")
        if p == "/guide.xml":
            return self._send(200, xmltv(), "application/xml")
        if p == "/guide.xml.gz":
            return self._send(200, gzip.compress(xmltv().encode("utf-8")), "application/gzip")
        if p == "/player_api.php":
            status, obj = xc_api(q)
            return self._send(status, json.dumps(obj), "application/json")
        if p == "/xmltv.php":
            return self._send(200, xmltv(), "application/xml")
        if p.startswith("/logo/"):
            return self._send(404, "no logo", "text/plain")  # exercises the monogram fallback
        m = re.match(r"^/(hls|slow)/([abc])/live\.m3u8$", p)
        if m:
            if m.group(1) == "slow":
                time.sleep(8)
            return self._send(200, live_playlist(m.group(2)), "application/vnd.apple.mpegurl")
        m = re.match(r"^/(?:hls|slow)/([abc])/seg/(seg_\d+\.ts)$", p)
        if m:
            return self._file(os.path.join(MEDIA, m.group(1), m.group(2)), "video/mp2t")
        m = re.match(r"^/ts/([abc])\.ts$", p)
        if m:
            return self._ts_stream(m.group(1))
        m = re.match(rf"^/(live|movie|series)/{USER}/{PASS}/(\d+)\.(\w+)$", p)
        if m:
            kind, sid, ext = m.group(1), int(m.group(2)), m.group(3)
            if kind == "live":
                variant = "abc"[(sid - 1) % 3]
                if ext == "m3u8":
                    return self._send(200, live_playlist(variant).replace("seg/", f"/hls/{variant}/seg/"),
                                      "application/vnd.apple.mpegurl")
                return self._ts_stream(variant)
            return self._file(os.path.join(MEDIA, "vod.mp4"), "video/mp4")
        if p == "/health":
            return self._send(200, "ok", "text/plain")
        return self._send(404, "not found", "text/plain")


if __name__ == "__main__":
    srv = ThreadingHTTPServer(("0.0.0.0", PORT), Handler)
    srv.daemon_threads = True
    print(f"mock provider on :{PORT}, base {BASE}, segments/channel {len(SEGMENTS['a'])}", flush=True)
    srv.serve_forever()
