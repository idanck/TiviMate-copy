"""Draw Shidur's launcher icon and TV banner (option D) into app/src/main/res.

The geometry is the one in ICON.md and in canvas/AppIcon.dc.html and canvas/AppBanner.dc.html
(variant d). A vector drawable cannot use a font, so the letters are read out of
res/font/karantina_bold.ttf and written as paths; the PNGs are rasterised from the same paths,
so every file is drawn from one composition.

Run it from the repository root after changing the design, and commit what it writes:

    python3 -m venv /tmp/icon-venv && /tmp/icon-venv/bin/pip install fonttools uharfbuzz resvg-py
    /tmp/icon-venv/bin/python docs/design/studio/render_icon.py
"""

from __future__ import annotations

from pathlib import Path

import resvg_py
import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[3]
RES = ROOT / "app/src/main/res"
FONT = RES / "font/karantina_bold.ttf"

TALLY = "#FF5A5F"
INK = "#F3F5F9"
GROUND = "#080C14"

# The adaptive icon is drawn on 108dp; the launcher shows the middle 72dp through its mask.
ICON_CANVAS = 108
ICON_VISIBLE = (18, 18, 72, 72)
LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
# The canvas's "rounded" shape: a corner of 22% of the side.
LEGACY_SQUARE_RADIUS = 0.22

BANNER_SIZES = {"mdpi": (160, 90), "xhdpi": (320, 180)}

GENERATED = "Generated by docs/design/studio/render_icon.py. Edit the script, not this file."


def number(n: float) -> str:
    text = f"{n:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def text_path(text: str, size: float, centre_x: float, baseline: float) -> str:
    """The outline of [text] as SVG path data, centred on its advance like `text-anchor: middle`.

    Shaped by HarfBuzz, the same engine a browser uses for the canvas, so a Hebrew word comes out
    in visual order (right to left) with whatever kerning the font carries.
    """
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    scale = size / font["head"].unitsPerEm

    face = hb.Face(hb.Blob.from_file_path(str(FONT)))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(hb.Font(face), buf)

    advance = sum(pos.x_advance for pos in buf.glyph_positions) * scale
    pen_x = centre_x - advance / 2
    svg = SVGPathPen(glyphs, ntos=number)
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = font.getGlyphName(info.codepoint)
        dx = pen_x + pos.x_offset * scale
        dy = baseline - pos.y_offset * scale
        glyphs[name].draw(TransformPen(svg, (scale, 0, 0, -scale, dx, dy)))
        pen_x += pos.x_advance * scale
    return svg.getCommands()


def rounded_rect_path(x: float, y: float, w: float, h: float, r: float) -> str:
    n = number
    return (
        f"M{n(x + r)},{n(y)}H{n(x + w - r)}A{n(r)},{n(r)} 0 0 1 {n(x + w)},{n(y + r)}"
        f"V{n(y + h - r)}A{n(r)},{n(r)} 0 0 1 {n(x + w - r)},{n(y + h)}"
        f"H{n(x + r)}A{n(r)},{n(r)} 0 0 1 {n(x)},{n(y + h - r)}"
        f"V{n(y + r)}A{n(r)},{n(r)} 0 0 1 {n(x + r)},{n(y)}Z"
    )


SHIN = text_path("ש", size=64, centre_x=54, baseline=70)
ICON_BAR = rounded_rect_path(38, 74, 32, 5, 2.5)
WORD = text_path("שידור", size=96, centre_x=160, baseline=118)
BANNER_BAR = rounded_rect_path(104, 128, 112, 7, 3.5)


def vector(paths: list[tuple[str, str, str]]) -> str:
    body = "".join(
        f"    <!-- {comment} -->\n"
        f"    <path\n"
        f'        android:fillColor="{colour}"\n'
        f'        android:pathData="{data}" />\n'
        for comment, colour, data in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{ICON_CANVAS}dp"\n'
        f'    android:height="{ICON_CANVAS}dp"\n'
        f'    android:viewportWidth="{ICON_CANVAS}"\n'
        f'    android:viewportHeight="{ICON_CANVAS}">\n'
        f"{body}"
        "</vector>\n"
    )


def write_vectors() -> None:
    shin = "ש (U+05E9), Karantina Bold at 64, baseline y=70, advance centred on x=54"
    bar = "The bar: x=38 y=74, 32 by 5, corner radius 2.5"
    (RES / "drawable/ic_launcher_foreground.xml").write_text(
        vector([(shin, INK, SHIN), (bar, GROUND, ICON_BAR)]), encoding="utf-8"
    )
    # Android 13 themed icons use this layer as a mask and tint it, so its colour is only alpha.
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector([(shin, "#FFFFFFFF", SHIN), (bar, "#FFFFFFFF", ICON_BAR)]), encoding="utf-8"
    )


def icon_svg(clip: str) -> str:
    x, y, w, h = ICON_VISIBLE
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}">'
        f'<clipPath id="mask">{clip}</clipPath>'
        f'<g clip-path="url(#mask)">'
        f'<rect width="{ICON_CANVAS}" height="{ICON_CANVAS}" fill="{TALLY}"/>'
        f'<path d="{SHIN}" fill="{INK}"/><path d="{ICON_BAR}" fill="{GROUND}"/>'
        f"</g></svg>"
    )


def banner_svg() -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 180">'
        f'<rect width="320" height="180" fill="{TALLY}"/>'
        f'<path d="{WORD}" fill="{INK}"/><path d="{BANNER_BAR}" fill="{GROUND}"/>'
        "</svg>"
    )


def render(svg: str, width: int, height: int, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(bytes(resvg_py.svg_to_bytes(svg_string=svg, width=width, height=height)))


def write_pngs() -> None:
    x, y, w, _ = ICON_VISIBLE
    r = w * LEGACY_SQUARE_RADIUS
    square = icon_svg(f'<rect x="{x}" y="{y}" width="{w}" height="{w}" rx="{number(r)}"/>')
    circle = icon_svg(f'<circle cx="{x + w / 2}" cy="{y + w / 2}" r="{w / 2}"/>')
    for density, size in LEGACY_SIZES.items():
        render(square, size, size, RES / f"mipmap-{density}/ic_launcher.png")
        render(circle, size, size, RES / f"mipmap-{density}/ic_launcher_round.png")
    for density, (width, height) in BANNER_SIZES.items():
        render(banner_svg(), width, height, RES / f"drawable-{density}/tv_banner.png")


if __name__ == "__main__":
    write_vectors()
    write_pngs()
